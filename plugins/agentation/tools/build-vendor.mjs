// Rebuilds ui/agentation.vendor.js from an unpacked `agentation` npm package: node tools/build-vendor.mjs <package dir>
// The result is one function of React and ReactDOM, so the page keeps a single React. Run it, then enable the plugin again: its files changed.
import { copyFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { rolldown } from 'rolldown';

const pkg = process.argv[2];
if (!pkg) throw new Error('usage: build-vendor.mjs <dir of the agentation package>');
const root = join(import.meta.dirname, '..');

const bundle = await rolldown({
  input: join(pkg, 'dist/index.mjs'),
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  transform: { define: { 'process.env.NODE_ENV': '"production"' } },
});
const { output } = await bundle.generate({
  format: 'iife',
  name: '__agentation',
  globals: { react: '__React', 'react-dom': '__ReactDOM', 'react/jsx-runtime': '__jsx' },
  minify: true,
});
await bundle.close();

writeFileSync(join(root, 'ui/agentation.vendor.js'), `/* agentation, (c) 2026 Benji Taylor, PolyForm Shield 1.0.0: see LICENSE.agentation. Generated by tools/build-vendor.mjs. */
export function load(__React, __ReactDOM) {
  const make = (type, props, key) => __React.createElement(type, key === undefined ? props : { ...props, key });
  const __jsx = { Fragment: __React.Fragment, jsx: make, jsxs: make };
  ${output[0].code}
  return __agentation;
}
`);
copyFileSync(join(pkg, 'LICENSE'), join(root, 'LICENSE.agentation'));
