import assert from 'node:assert/strict';
import { readFileSync, symlinkSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, beforeEach, test } from 'node:test';
import type { MemoryApi } from '../context.ts';
import { createGuard, noteGuardHooks, type GuardDecision } from './guard.ts';
import { LINT_LIMITS, lintNote } from './lint.ts';
import { createStore, type Store } from './store.ts';
import { makeKit, type TestKit } from './testkit.ts';
import { setWikiManaged } from './wikiManaged.ts';

let kit: TestKit;
let dir: string;
beforeEach(() => {
  kit = makeKit();
  dir = join(kit.paths.vault, 'projects', 'p');
});
afterEach(() => kit.close());

const note = (o: { name?: string; description?: string; type?: string; tags?: string; body?: string } = {}) =>
  `---\nname: ${o.name ?? 'zebra-habitat'}\ndescription: ${o.description ?? 'Where the zebra lives'}\nmetadata:\n  type: ${o.type ?? 'project'}\n  tags: ${o.tags ?? '[zoo]'}\n---\n${o.body ?? 'The zebra lives in the savanna.\n'}`;
const guard = (store: Store = createStore(kit.ctx)) => createGuard(kit.ctx, store);
const check = (tool: string, input: Record<string, unknown>, cwd = kit.base) => guard().check('tab-1', cwd, tool, input);

test('write of a malformed vault note is denied with one line per issue', () => {
  const path = join(dir, 'zebra-habitat.md');
  const content = '---\nname: zebra-habitat\nmetadata:\n  type: note\n---\nThe zebra lives in the savanna.\n';
  const d = check('Write', { file_path: path, content });
  assert.equal(d?.decision, 'deny');
  const expected = lintNote(path, content, createStore(kit.ctx).lintCtx(path)).issues.filter((i) => i.reject).map((i) => i.message);
  assert.equal(expected.length, 3);
  assert.deepEqual(d.reason.split('\n'), expected);
  assert.equal(check('Write', { file_path: path, content: note() }), null);
});

test('edit is checked on the resulting text', () => {
  const path = kit.write(join(dir, 'zebra-habitat.md'), note({ body: 'The zebra ZZ lives in the savanna ZZ.\n' }));
  const long = 'a'.repeat(1600);
  assert.equal(check('Edit', { file_path: path, old_string: 'ZZ', new_string: long }), null, 'one replacement stays under the max');
  const d = check('Edit', { file_path: path, old_string: 'ZZ', new_string: long, replace_all: true });
  assert.equal(d?.decision, 'deny');
  assert.match(d.reason, /^body is \d+ chars; max 3000/);
  const tooLong = check('Edit', { file_path: path, old_string: 'Where the zebra lives', new_string: 'x'.repeat(121) });
  assert.match(tooLong?.reason ?? '', /^description is 121 chars; max 120/);
});

test('multiedit applies all edits in order', () => {
  const path = kit.write(join(dir, 'zebra-habitat.md'), note());
  const edits = [{ old_string: 'tags: [zoo]', new_string: 'tags: [zoo, x]' }, { old_string: 'x]', new_string: 'x, y, z]' }];
  const d = check('MultiEdit', { file_path: path, edits });
  assert.equal(d?.decision, 'deny');
  assert.match(d.reason, /^metadata\.tags has 4;/);
  assert.equal(check('MultiEdit', { file_path: path, edits: [...edits].reverse() }), null, 'the second edit first finds nothing');
});

test('mechanical defects are allowed', () => {
  const content = note({ name: 'Zebra_Habitat', tags: '[Zoo, zoo]' }).replace(/\n/g, '\r\n');
  assert.equal(check('Write', { file_path: join(dir, 'zebra-habitat.md'), content }), null);
});

test('MEMORY.md, _index and _log writes are denied', () => {
  setWikiManaged(kit.paths, 'p', true);
  for (const rel of ['projects/p/MEMORY.md', '_index/p.md', '_log/p.md']) {
    const d = check('Write', { file_path: join(kit.paths.vault, rel), content: note() });
    assert.deepEqual(d, { decision: 'deny', reason: `${rel} is generated by Claude OS; write or edit the note instead` });
  }
  const path = kit.write(join(dir, 'MEMORY.md'), '- [a](a.md) — a\n');
  assert.equal(check('Edit', { file_path: path, old_string: 'a', new_string: 'b' })?.decision, 'deny');
});

// Before its wiki migration a project keeps its old notes: an edit may not add a reject, but old ones stay.
const RUSSIAN = note({ body: 'Зебра живёт в саванне и пьёт воду из реки.\n' });

test('edit of an unmanaged note adds no new issue → null', () => {
  const path = kit.write(join(dir, 'zebra-habitat.md'), RUSSIAN);
  assert.equal(check('Edit', { file_path: path, old_string: 'реки', new_string: 'озера' }), null);
  assert.equal(check('MultiEdit', { file_path: path, edits: [{ old_string: 'Зебра', new_string: 'Зебры' }] }), null);
});

test('edit of an unmanaged note that adds a new reject code → deny', () => {
  const path = kit.write(join(dir, 'zebra-habitat.md'), RUSSIAN);
  const d = check('Edit', { file_path: path, old_string: 'Where the zebra lives', new_string: 'x'.repeat(121) });
  assert.equal(d?.decision, 'deny');
  assert.deepEqual(d.reason.split('\n'), ['description is 121 chars; max 120: shorten it to the question the note answers']);
  const fresh = check('Write', { file_path: join(dir, 'zebra-water.md'), content: note({ name: 'zebra-water', body: 'Зебра пьёт воду из реки.\n' }) });
  assert.equal(fresh?.decision, 'deny', 'a new note is checked fully');
  assert.match(fresh.reason, /write the note in English/);
});

test('write over an existing unmanaged note is denied only for a new reject code', () => {
  const path = kit.write(join(dir, 'zebra-habitat.md'), RUSSIAN);
  assert.equal(check('Write', { file_path: path, content: RUSSIAN.replace('реки', 'озера') }), null);
  const d = check('Write', { file_path: path, content: RUSSIAN.replace('Where the zebra lives', 'x'.repeat(121)) });
  assert.equal(d?.decision, 'deny');
  assert.deepEqual(d.reason.split('\n'), ['description is 121 chars; max 120: shorten it to the question the note answers']);
  setWikiManaged(kit.paths, 'p', true);
  assert.equal(check('Write', { file_path: path, content: RUSSIAN.replace('реки', 'озера') })?.decision, 'deny', 'managed: checked fully');
});

test('MEMORY.md of an unmanaged project is not denied', () => {
  assert.equal(check('Write', { file_path: join(dir, 'MEMORY.md'), content: '- [a](a.md) — a\n' }), null);
  const path = kit.write(join(dir, 'MEMORY.md'), '- [a](a.md) — a\n');
  assert.equal(check('Edit', { file_path: path, old_string: 'a', new_string: 'b' }), null);
  for (const rel of ['_index/p.md', '_log/p.md']) assert.equal(check('Write', { file_path: join(kit.paths.vault, rel), content: 'x' })?.decision, 'deny', rel);
});

test('managed behaviour unchanged', () => {
  setWikiManaged(kit.paths, 'p', true);
  const path = kit.write(join(dir, 'zebra-habitat.md'), RUSSIAN);
  const d = check('Edit', { file_path: path, old_string: 'реки', new_string: 'озера' });
  assert.equal(d?.decision, 'deny');
  assert.match(d.reason, /write the note in English/);
  assert.equal(check('Write', { file_path: join(dir, 'MEMORY.md'), content: '- [a](a.md) — a\n' })?.decision, 'deny');
});

test('paths outside the vault get no decision', () => {
  const bad = 'no frontmatter, на русском';
  assert.equal(check('Write', { file_path: join(kit.base, 'elsewhere', 'projects', 'p', 'x.md'), content: bad }), null);
  assert.equal(check('Write', { file_path: join(kit.paths.vault, 'projects', 'p.md'), content: bad }), null, 'not inside a project');
  assert.equal(check('Write', { file_path: join(dir, 'notes.txt'), content: bad }), null, 'not a note');
  const path = kit.write(join(dir, 'zebra-habitat.md'), bad);
  assert.equal(check('Read', { file_path: path }), null);
});

test('relative path resolves against cwd', () => {
  const content = 'no frontmatter';
  assert.equal(check('Write', { file_path: 'p/zebra-habitat.md', content }, join(kit.paths.vault, 'projects'))?.decision, 'deny');
  assert.equal(check('Write', { file_path: '../vault/projects/p/zebra-habitat.md', content }, join(kit.base, 'work'))?.decision, 'deny');
  assert.equal(check('Write', { file_path: 'p/zebra-habitat.md', content }, kit.base), null);
});

test('a symlinked vault path is recognized', () => {
  const real = kit.paths.vault;
  kit.write(join(real, 'projects', 'p', '.keep'), '');
  kit.paths.vault = join(kit.base, 'vault-link');
  symlinkSync(real, kit.paths.vault);
  const content = 'no frontmatter';
  assert.equal(check('Write', { file_path: join(real, 'projects', 'p', 'zebra-habitat.md'), content })?.decision, 'deny', 'the real path');
  assert.equal(check('Write', { file_path: join(kit.paths.vault, 'projects', 'p', 'zebra-habitat.md'), content })?.decision, 'deny', 'the link');
});

test('old_string not found gives no decision', () => {
  const path = kit.write(join(dir, 'zebra-habitat.md'), note());
  assert.equal(check('Edit', { file_path: path, old_string: 'absent', new_string: 'на русском '.repeat(20) }), null);
  assert.equal(check('Edit', { file_path: join(dir, 'missing.md'), old_string: 'a', new_string: 'b' }), null, 'no file to edit');
});

test('a guard error gives no decision', () => {
  const broken = { lintCtx: () => { throw new Error('boom'); } } as unknown as Store;
  assert.equal(guard(broken).check('tab-1', kit.base, 'Write', { file_path: join(dir, 'zebra-habitat.md'), content: 'no frontmatter' }), null);
  assert.equal(check('Write', { file_path: 42, content: 'x' }), null);
  assert.equal(check('MultiEdit', { file_path: join(dir, 'zebra-habitat.md'), edits: 'nope' }), null);
});

test('note rules match the validator', () => {
  const rules = readFileSync(join(import.meta.dirname, '../../root/NOTE_RULES.md'), 'utf8');
  const L = LINT_LIMITS;
  assert.ok(rules.trimEnd().split('\n').length <= 25, `${rules.split('\n').length} lines`);
  for (const s of [`≤${L.descriptionMax}`, String(L.bodySoft), L.types.join(' | '), `${L.tagsMin}–${L.tagsMax}`, 'memory_search']) {
    assert.ok(rules.includes(s), s);
  }
});

test('the hook maps a decision to the SDK output', async () => {
  const calls: unknown[][] = [];
  let decision: GuardDecision = { decision: 'deny', reason: 'why' };
  const memory = { guardTool: (...a: unknown[]) => { calls.push(a); return decision; } } as unknown as MemoryApi;
  const [matcher] = noteGuardHooks(memory, 'tab-1')!.PreToolUse!;
  assert.equal(matcher.matcher, 'Read|Write|Edit|MultiEdit');
  const input = { hook_event_name: 'PreToolUse', cwd: '/w', tool_name: 'Write', tool_input: { file_path: 'x.md' }, tool_use_id: 'u', session_id: 's', transcript_path: '/t' } as const;
  const signal = new AbortController().signal;
  assert.deepEqual(await matcher.hooks[0](input, 'u', { signal }), { hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: 'why' } });
  assert.deepEqual(calls[0], ['tab-1', '/w', 'Write', { file_path: 'x.md' }]);
  decision = null;
  assert.deepEqual(await matcher.hooks[0](input, 'u', { signal }), {});
});
