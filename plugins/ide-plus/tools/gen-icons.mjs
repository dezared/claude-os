// Regenerates ui/icons.js from the free libraries in the app's node_modules: node plugins/ide-plus/tools/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const here = import.meta.dirname;
const modules = join(here, '..', '..', '..', 'node_modules');
const require = createRequire(join(modules, 'x.js'));
const brands = require('simple-icons');

// A brand's own colour, unless it would disappear on the dark panel.
const MUTED = '#b0b0b9';
const visible = (hex) => {
  const n = parseInt(hex, 16);
  const luma = (0.2126 * (n >> 16) + 0.7152 * ((n >> 8) & 255) + 0.0722 * (n & 255)) / 255;
  return luma < 0.3 ? MUTED : `#${hex}`;
};

function brand(slug) {
  const icon = Object.values(brands).find((b) => b.slug === slug);
  if (!icon) throw new Error(`no simple-icon ${slug}`);
  return { kind: 'fill', body: icon.path, color: visible(icon.hex) };
}

function outline(name, color = MUTED) {
  const source = readFileSync(join(modules, 'lucide-react', 'dist', 'esm', 'icons', `${name}.mjs`), 'utf8');
  const nodes = /node: (\[[\s\S]*?\n  \]),?\n/.exec(source);
  if (!nodes) throw new Error(`no lucide icon ${name}`);
  const parsed = new Function(`return ${nodes[1]}`)();
  return { kind: 'stroke', body: parsed.map(([tag, { key: _key, ...attrs }]) => [tag, attrs]), color };
}

