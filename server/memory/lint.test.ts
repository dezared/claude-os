import assert from 'node:assert/strict';
import { test } from 'node:test';
import { noteMeta, parseNote, serializeFrontmatter } from './frontmatter.ts';
import { lintNote, slugOf, type LintCtx } from './lint.ts';

// An empty vault: no names taken, no tags, no link resolves.
const ctx = (over: Partial<LintCtx> = {}): LintCtx => ({
  path: 'projects/p/note.md',
  project: 'p',
  names: new Map(),
  tags: [],
  resolves: () => false,
  ...over,
});

const note = (o: { name?: string; description?: string; meta?: string; body?: string } = {}) =>
  `---\nname: ${o.name ?? 'note'}\ndescription: ${o.description ?? 'Why the note exists and when to read it'}\nmetadata:\n${o.meta ?? '  type: feedback\n  tags: [db]\n'}---\n${o.body ?? 'Generate migrations with the diff tool, then review them.\n'}`;

const codes = (md: string, file = 'note.md', c = ctx()) => lintNote(file, md, c).issues.map((i) => i.code);
const rejected = (md: string, code: string, file = 'note.md', c = ctx()) => {
  const issue = lintNote(file, md, c).issues.find((i) => i.code === code);
  assert.ok(issue, `expected ${code}`);
  assert.equal(issue.reject, true);
};

const claudeShape = [
  '---',
  'name: db-migrations',
  'description: "How are migrations made: generated by the diff tool, never by hand"',
  'metadata:',
  '  node_type: memory',
  '  type: feedback',
  '  tags: [db]',
  '  originSessionId: 0b5c2f1e-1111-4222-8333-944445555666',
  '  modified: 2026-11-09T10:00:00.000Z',
  '  custom: x',
  '---',
  'Generate migrations with `doctrine:migrations:diff`, then review them.',
  '',
  '**Why:** hand-written migrations drift from the entities.',
  '**How to apply:** never write a migration file by hand.',
  '',
].join('\n');

test("claude code's own shape is left alone", () => {
  assert.deepEqual(lintNote('db-migrations.md', claudeShape, ctx()), { fixed: null, fixes: [], issues: [] });
});

test('claude code block lists and deeper indent are read', () => {
  const md = claudeShape.replace('  tags: [db]', '  tags:\n    - db\n    - review');
  assert.deepEqual(lintNote('db-migrations.md', md, ctx()), { fixed: null, fixes: [], issues: [] });
  assert.deepEqual(noteMeta(md).tags, ['db', 'review']);
});

test('parse then serialize keeps stamps and extra metadata keys', () => {
  const md = [
    '---',
    'name: db-migrations',
    'description: "How are migrations made: generated by the diff tool, never by hand"',
    'metadata:',
    '  type: feedback',
    '  tags: [db, review]',
    '  node_type: memory',
    '  originSessionId: 0b5c2f1e-1111-4222-8333-944445555666',
    '  modified: 2026-11-09T10:00:00.000Z',
    '  custom: x',
    '---',
    'Body.',
    '',
  ].join('\n');
  const { fm, body } = parseNote(md);
  assert.ok(fm);
  assert.equal(serializeFrontmatter(fm) + body, md);
  assert.deepEqual(fm.metadata, {
    type: 'feedback',
    tags: ['db', 'review'],
    node_type: 'memory',
    originSessionId: '0b5c2f1e-1111-4222-8333-944445555666',
    modified: '2026-11-09T10:00:00.000Z',
    custom: 'x',
  });
});

test('parseNote reads quoted, block and CRLF values', () => {
  const { fm, body } = parseNote("---\r\nname: 'it''s'\r\ndescription: >\r\n  one\r\n  two\r\nlist: [a, \"b, c\"]\r\n---\r\nbody");
  assert.deepEqual(fm, { name: "it's", description: 'one two', list: ['a', 'b, c'] });
  assert.equal(body, 'body');
  assert.deepEqual(parseNote('no frontmatter'), { fm: null, body: 'no frontmatter' });
});

test('serializer quotes values that YAML would misread', () => {
  const out = serializeFrontmatter({ name: 'n', description: 'a: b', metadata: { type: 'user', tags: ['x'], a: ' lead', b: 'see #1', c: '- dash', d: 'plain' } });
  assert.equal(out, '---\nname: n\ndescription: "a: b"\nmetadata:\n  type: user\n  tags: [x]\n  a: " lead"\n  b: "see #1"\n  c: "- dash"\n  d: plain\n---\n');
  assert.deepEqual(parseNote(out + 'x').fm?.metadata, { type: 'user', tags: ['x'], a: ' lead', b: 'see #1', c: '- dash', d: 'plain' });
});

test('noteMeta reads metadata and falls back to the old top-level type', () => {
  const meta = noteMeta(claudeShape);
  assert.equal(meta.name, 'db-migrations');
  assert.equal(meta.type, 'feedback');
  assert.deepEqual(meta.tags, ['db']);
  assert.equal(meta.modified, Date.parse('2026-11-09T10:00:00.000Z'));
  assert.equal(meta.hasFrontmatter, true);
  assert.equal(noteMeta('---\nname: a\ntype: project\n---\nb').type, 'project');
  assert.deepEqual(noteMeta('just text'), { name: null, description: null, type: null, tags: [], modified: null, body: 'just text', hasFrontmatter: false });
});

test('slugOf lowercases, kebab-cases and drops the rest', () => {
  assert.equal(slugOf('Project_Event'), 'project-event');
  assert.equal(slugOf('a  b__c'), 'a-b-c');
  assert.equal(slugOf('Wiki (v2)!'), 'wiki-v2');
});

const fixCases: [string, string, string][] = [
  ['Project_Event.md', note({ name: 'foo' }), 'name-mismatch'],
  ['note.md', '---\nname: note\ndescription: Why the note exists\ntype: feedback\naliases: [old-note]\nmetadata:\n  tags: [db]\n---\nBody.\n', 'old-type'],
  ['note.md', note({ meta: '  type: feedback\n  tags: [DB, db, Code_Review]\n' }), 'tags-format'],
  ['note.md', note().replaceAll('\n', '\r\n').replace('review them.', 'review them.  '), 'whitespace'],
  ['note.md', note({ body: 'Generate migrations.   \nThen review.\t\n' }), 'whitespace'],
];

test('name is fixed to the slug of the file stem', () => {
  const r = lintNote('Project_Event.md', note({ name: 'foo' }), ctx());
  assert.ok(r.fixes.includes('name-mismatch'));
  assert.match(r.fixed ?? '', /^---\nname: project-event\n/);
});

test('old top-level type moves under metadata', () => {
  const r = lintNote('note.md', fixCases[1][1], ctx());
  assert.deepEqual(r.fixes, ['old-type']);
  assert.equal(r.fixed, '---\nname: note\ndescription: Why the note exists\nmetadata:\n  type: feedback\n  tags: [db]\n  aliases: [old-note]\n---\nBody.\n');
  assert.deepEqual(r.issues, []);
});

test('tags are lowercased, kebab-cased and deduplicated', () => {
  const r = lintNote('note.md', fixCases[2][1], ctx());
  assert.deepEqual(r.fixes, ['tags-format']);
  assert.deepEqual(noteMeta(r.fixed ?? '').tags, ['db', 'code-review']);
});

test('trailing spaces and CRLF are fixed', () => {
  const r = lintNote('note.md', fixCases[3][1], ctx());
  assert.deepEqual(r.fixes, ['whitespace']);
  assert.equal(r.fixed, note());
  assert.equal(lintNote('note.md', fixCases[4][1], ctx()).fixed, note({ body: 'Generate migrations.   \nThen review.\n' }), 'a hard line break stays');
});

test('markdown hard line breaks stay; trailing spaces of the frontmatter and a paragraph end go', () => {
  const breaks = note({ body: 'Generate migrations.  \nThen review them.\n' });
  assert.deepEqual(lintNote('note.md', breaks, ctx()), { fixed: null, fixes: [], issues: [] });
  const crlf = note({ description: 'Why the note exists  ', body: 'Generate migrations.  \nThen review them.  \n\nDone.  \n' }).replaceAll('\n', '\r\n');
  const r = lintNote('note.md', crlf, ctx());
  assert.deepEqual(r.fixes, ['whitespace']);
  assert.equal(r.fixed, note({ description: 'Why the note exists', body: 'Generate migrations.  \nThen review them.\n\nDone.\n' }));
});

test('a reject never blocks the fixes', () => {
  const r = lintNote('Big_Note.md', note({ name: 'x', body: 'y'.repeat(3001) }), ctx());
  assert.deepEqual(r.fixes, ['name-mismatch']);
  assert.ok(r.fixed);
  assert.ok(r.issues.some((i) => i.code === 'body-long'));
});

test('reject: no frontmatter', () => rejected('Just a body.\n', 'no-frontmatter'));
test('reject: no description', () => rejected('---\nname: note\nmetadata:\n  type: user\n  tags: [db]\n---\nBody.\n', 'no-description'));
test('reject: description of 121 chars', () => rejected(note({ description: 'd'.repeat(121) }), 'description-long'));
test('reject: multi-line description', () => rejected(note({ description: '|\n  line one\n  line two' }), 'description-multiline'));
test('reject: type outside the enum', () => rejected(note({ meta: '  type: note\n  tags: [db]\n' }), 'bad-type'));
test('reject: 0 tags', () => rejected(note({ meta: '  type: user\n  tags: []\n' }), 'tags-count'));
test('reject: 4 tags', () => rejected(note({ meta: '  type: user\n  tags: [a, b, c, d]\n' }), 'tags-count'));
test('reject: generic name', () => rejected(note({ name: 'decisions' }), 'name-generic', 'decisions.md'));
test('reject: name taken by another note', () => {
  const c = ctx({ names: new Map([['note', ['projects/other/note.md']]]) });
  rejected(note(), 'name-duplicate', 'note.md', c);
  assert.ok(!codes(note(), 'note.md', ctx({ names: new Map([['note', ['projects/p/note.md']]]) })).includes('name-duplicate'));
});
test('reject: name over 60 chars', () => rejected(note({ name: 'n'.repeat(61) }), 'name-long', `${'n'.repeat(61)}.md`));
test('reject: body of 3001 chars', () => rejected(note({ body: 'b'.repeat(3001) }), 'body-long'));
test('reject: a Russian body', () => rejected(note({ body: 'Миграции генерируются через diff и проверяются вручную.\n' }), 'not-english'));

test('body over 1500 is a flag', () => {
  const issues = lintNote('note.md', note({ body: 'b'.repeat(1501) }), ctx()).issues;
  assert.deepEqual(issues.map((i) => [i.code, i.reject]), [['body-soft', false]]);
});

test('quotes and code do not count as non-English', () => {
  const body = 'The owner said "не трогай миграции руками" and «сначала diff» twice.\n\n```\nкомментарий в коде на русском языке, длинный\n```\nRun `генерация` first.\n';
  assert.ok(!codes(note({ body })).includes('not-english'));
});

test('unresolved link is a flag', () => {
  const issues = lintNote('note.md', note({ body: 'See [[missing]] and [[found]].\n' }), ctx({ resolves: (n) => n === 'found' })).issues;
  assert.deepEqual(issues.map((i) => [i.code, i.reject]), [['link-unresolved', false]]);
  assert.match(issues[0].message, /\[\[missing\]\]/);
  assert.doesNotMatch(issues[0].message, /found/);
});

test('messages say what to do', () => {
  const long = lintNote('note.md', note({ description: 'd'.repeat(164) }), ctx()).issues.find((i) => i.code === 'description-long');
  assert.equal(long?.message, 'description is 164 chars; max 120: shorten it to the question the note answers');
  const tags = Array.from({ length: 25 }, (_, i) => `t${i}`);
  const count = lintNote('note.md', note({ meta: '  type: user\n  tags: []\n' }), ctx({ tags })).issues.find((i) => i.code === 'tags-count');
  assert.ok(count?.message.endsWith(`existing tags in p: ${tags.slice(0, 20).join(', ')}`), count?.message);
  const body = lintNote('note.md', note({ body: 'b'.repeat(3400) }), ctx()).issues.find((i) => i.code === 'body-long');
  assert.equal(body?.message, 'body is 3400 chars; max 3000: split it into notes, one fact each');
  for (const i of lintNote('x.md', 'Текст без frontmatter.\n', ctx()).issues) assert.doesNotMatch(i.message, /\n/);
});

test('lint is idempotent', () => {
  for (const [file, md, code] of fixCases) {
    const r = lintNote(file, md, ctx());
    assert.ok(r.fixes.includes(code), code);
    assert.ok(r.fixed, code);
    const again = lintNote(file, r.fixed, ctx());
    assert.equal(again.fixed, null, code);
    assert.deepEqual(again.fixes, [], code);
  }
});
