import assert from 'node:assert/strict';
import { afterEach, beforeEach, test } from 'node:test';
import { createSearchIndex, formatHits, toMatch, type SearchDoc } from './search.ts';

let index: ReturnType<typeof createSearchIndex>;
beforeEach(() => { index = createSearchIndex(); });
afterEach(() => index.close());

const doc = (over: Partial<SearchDoc> & { path: string }): SearchDoc => ({
  id: over.path,
  project: 'a',
  type: 'project',
  name: 'note',
  description: null,
  tags: [],
  body: '',
  mtime: 1,
  sha: over.path,
  ...over,
});
const names = (q: string, opts?: Parameters<typeof index.query>[1]) => index.query(q, opts).map((h) => h.name);

test('sync adds, changes, deletes and renames', () => {
  const one = doc({ path: '/v/one.md', name: 'one', body: 'apples grow here', sha: '1' });
  const two = doc({ path: '/v/two.md', name: 'two', body: 'pears grow here', sha: '2' });
  assert.deepEqual(index.sync([one, two]), { added: 2, changed: 0, removed: 0 });
  assert.deepEqual(names('grow').sort(), ['one', 'two']);

  assert.deepEqual(index.sync([one, two]), { added: 0, changed: 0, removed: 0 });

  const oneChanged = { ...one, body: 'plums grow here', sha: '1b' };
  assert.deepEqual(index.sync([oneChanged, two]), { added: 0, changed: 1, removed: 0 });
  assert.deepEqual(names('apples'), []);
  assert.deepEqual(names('plums'), ['one']);

  assert.deepEqual(index.sync([oneChanged]), { added: 0, changed: 0, removed: 1 });
  assert.deepEqual(names('pears'), []);

  const renamed = { ...oneChanged, path: '/v/three.md', id: '/v/three.md', name: 'three' };
  assert.deepEqual(index.sync([renamed]), { added: 1, changed: 0, removed: 1 });
  const hits = index.query('plums');
  assert.deepEqual(hits.map((h) => [h.name, h.path, h.id]), [['three', '/v/three.md', '/v/three.md']]);
});

test('prefix match: migration finds migrations', () => {
  index.sync([doc({ path: '/v/m.md', name: 'm', body: 'all migrations are generated by hand' })]);
  assert.deepEqual(names('migration'), ['m']);
});

test('AND first, OR when AND finds nothing', () => {
  index.sync([
    doc({ path: '/v/both.md', name: 'both', body: 'redis cache and queue' }),
    doc({ path: '/v/cache.md', name: 'cache', body: 'redis cache only' }),
    doc({ path: '/v/queue.md', name: 'queue', body: 'kafka queue only' }),
  ]);
  assert.deepEqual(names('redis queue'), ['both']);
  assert.deepEqual(names('kafka cache').sort(), ['both', 'cache', 'queue']);
  assert.equal(toMatch('redis queue', 'AND'), '"redis"* AND "queue"*');
  assert.equal(toMatch('redis queue', 'OR'), '"redis"* OR "queue"*');
  assert.equal(toMatch('- x *', 'AND'), null);
});

test('name outranks body', () => {
  index.sync([
    doc({ path: '/v/body.md', name: 'other', body: 'deploy deploy deploy steps', mtime: 2 }),
    doc({ path: '/v/deploy.md', name: 'deploy', body: 'steps', mtime: 1 }),
  ]);
  assert.deepEqual(names('deploy'), ['deploy', 'other']);
});

test('caller project is boosted', () => {
  index.sync([
    doc({ path: '/v/a.md', project: 'a', name: 'same', body: 'shared fact', mtime: 2 }),
    doc({ path: '/v/b.md', project: 'b', name: 'same', body: 'shared fact', mtime: 1 }),
  ]);
  assert.deepEqual(index.query('shared', { boost: 'b' }).map((h) => h.project), ['b', 'a']);
  assert.deepEqual(index.query('shared').map((h) => h.project), ['a', 'b']);
  assert.deepEqual(index.query('shared', { project: 'b' }).map((h) => h.project), ['b']);
  assert.deepEqual(index.query('shared', { project: null }).map((h) => h.project), ['a', 'b']);
});

test('limit defaults to 5 and is clamped to 1..20', () => {
  index.sync(Array.from({ length: 25 }, (_, i) => doc({ path: `/v/${i}.md`, name: `n${i}`, body: 'common word', mtime: i })));
  assert.equal(index.query('common').length, 5);
  assert.equal(index.query('common', { limit: 0 }).length, 1);
  assert.equal(index.query('common', { limit: 100 }).length, 20);
});

test('snippet is at most 160 chars and marked', () => {
  const body = Array.from({ length: 60 }, (_, i) => (i === 30 ? 'needle' : `longword${i}`)).join('\n');
  index.sync([doc({ path: '/v/s.md', name: 's', body })]);
  const [hit] = index.query('needle');
  assert.ok(hit.snippet.length <= 160, `${hit.snippet.length}`);
  assert.match(hit.snippet, /\[needle\]/);
  assert.doesNotMatch(hit.snippet, /\n/);

  index.sync([doc({ path: '/v/s.md', name: 's', sha: 'many', body: Array.from({ length: 40 }, (_, i) => `needlework${i}x`).join(' ') })]);
  const [many] = index.query('needle', { marks: ['\u0001', '\u0002'] });
  assert.ok(many.snippet.length <= 160, `${many.snippet.length}`);
  assert.equal(many.snippet.split('\u0001').length, many.snippet.split('\u0002').length, 'no dangling open mark');
});

test('cyrillic is case-folded', () => {
  index.sync([doc({ path: '/v/c.md', name: 'c', body: 'Миграции пишет владелец' })]);
  assert.deepEqual(names('миграции'), ['c']);
  assert.deepEqual(names('ВЛАДЕЛЕЦ'), ['c']);
});

test('hostile query is literal', () => {
  index.sync([doc({ path: '/v/h.md', name: 'h', body: 'drop table docs near tags db' })]);
  for (const q of ['"; DROP TABLE docs; --', 'NEAR(a b)', 'tags:db', 'a*', '-', 'x']) {
    assert.doesNotThrow(() => index.query(q), q);
  }
  assert.deepEqual(names('x'), []);
  assert.deepEqual(names('"; DROP TABLE docs; --'), ['h']);
  assert.deepEqual(names('tags:db'), ['h']);
  assert.deepEqual(index.sync([doc({ path: '/v/h.md', name: 'h', body: 'drop table docs near tags db' })]), { added: 0, changed: 0, removed: 0 });
});

test('api markers survive brackets in text', () => {
  index.sync([doc({ path: '/v/l.md', name: 'l', body: 'see [[link]] and [x]' })]);
  const [hit] = index.query('see', { marks: ['\u0001', '\u0002'] });
  assert.equal(hit.snippet, '\u0001see\u0002 [[link]] and [x]');
});

test('tool text has one block per hit and the path', () => {
  index.sync([
    doc({ path: '/v/a/one.md', project: 'a', type: 'feedback', name: 'one', description: 'Answers one', body: 'topic text', mtime: 2 }),
    doc({ path: '/v/two.md', project: null, type: null, name: 'two', body: 'topic text padded with several more words', mtime: 1 }),
  ]);
  const text = formatHits(index.query('topic'));
  assert.equal(text, [
    'a/one [feedback] — Answers one', '  [topic] text', '  /v/a/one.md',
    '',
    'global/two [-] — ', '  [topic] text padded with several more words', '  /v/two.md',
  ].join('\n'));
  assert.equal(formatHits([]), 'No notes match. Try other English keywords, or project "*".');
});
